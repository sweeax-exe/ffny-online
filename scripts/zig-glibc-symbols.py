#!/usr/bin/env python3
"""Write setup/linux/glibc-symbols.h for the pinned Zig (setup/dependencies-linux.json, toolchain).

    scripts/zig-glibc-symbols.py <payload tools folder>

Zig links its own runtime (compiler_rt) into every program, and that runtime also defines memcpy,
memset, strlen, floor, fmod, sin and other functions glibc has. They are weak, but a definition in
the program still wins over the C library's, so once anything pulls the runtime in (128-bit
arithmetic does), the game's calls go to Zig's generic versions instead of glibc's tuned ones:
the Steam Deck's scene loads were 17-20% longer. The header names glibc's version of each such
function (`.symver floor, floor@GLIBC_2.2.5`), which only the C library can supply; the payload's
zig-cc and zig-c++ wrappers include it in everything they compile.

Run it when the Zig pin changes, with a staged tools/ (scripts/linux_payload.py), on Linux with
binutils' nm. Each name is linked on its own, so a name glibc lacks leaves no version behind.
"""
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'setup/linux/glibc-symbols.h'


def runtime_names(zig):
    """Every function Zig's runtime exports, from its sources."""
    names = set()
    for path in [zig / 'lib/compiler_rt.zig', *(zig / 'lib/compiler_rt').glob('*.zig')]:
        text = path.read_text(encoding='utf-8')
        names.update(re.findall(r'symbol\((?:if [^,]*else )?&\w+, "(\w+)"\)', text))
        names.update(re.findall(r'"(__\w+_chk|__stack_chk_fail|__chk_fail)"', text))
    return sorted(names)


def glibc_version(tools, name, work, env):
    """The version glibc gives `name` (`name@GLIBC_x`) for the wrappers' target, or None."""
    source = work / 'one.c'
    source.write_text(f'extern char {name}(); void *p = (void *){name};\nint main(void) {{ return 0; }}\n')
    if subprocess.run([tools / 'bin/zig-cc', '-w', '-fno-builtin', source, '-o', work / 'one', '-lm'], env=env,
                      stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode:
        return None
    symbols = subprocess.run(['nm', '-D', work / 'one'], capture_output=True, text=True, check=True).stdout
    return next((s for kind, s in (line.split()[-2:] for line in symbols.splitlines() if len(line.split()) >= 2)
                 if kind == 'U' and s.startswith(name + '@GLIBC_')), None)


def main():
    tools = Path(sys.argv[1]).resolve()
    zig = tools / 'zig'
    pins = json.loads((ROOT / 'setup/dependencies-linux.json').read_text(encoding='utf-8'))['toolchain']
    version = subprocess.run([zig / 'zig', 'version'], capture_output=True, text=True, check=True).stdout.strip()
    with tempfile.TemporaryDirectory() as folder:
        work = Path(folder)
        env = dict(os.environ, ZIG_GLOBAL_CACHE_DIR=str(work / 'cache'), ZIG_LOCAL_CACHE_DIR=str(work / 'cache'))
        bound = [v for v in (glibc_version(tools, n, work, env) for n in runtime_names(zig)) if v]
    lines = [f'/* Generated by scripts/zig-glibc-symbols.py for Zig {version} and glibc {pins["glibc"]}: do not edit.',
             ' * The functions Zig\'s runtime defines that glibc also has, bound to glibc\'s own (the script',
             ' * says why). The payload\'s zig-cc and zig-c++ include this in everything they compile. */',
             '#if !defined(__ASSEMBLER__) && !defined(DEFJAM_GLIBC_SYMBOLS_H)', '#define DEFJAM_GLIBC_SYMBOLS_H']
    lines += ['__asm__(".symver %s, %s");' % (s.split('@')[0], s) for s in sorted(bound)]
    lines += ['#endif', '']
    HEADER.write_text('\n'.join(lines), encoding='utf-8')
    print(f'{HEADER.relative_to(ROOT)}: {len(bound)} functions')


if __name__ == '__main__':
    main()
